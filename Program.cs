
using System;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using System.Collections.Generic;
using System.Linq;

class BasicCompiler
{
    private string[] lines;
    private List<string> errors = new List<string>();
    private Dictionary<string, string> variables = new Dictionary<string, string>();
    private HashSet<string> labels = new HashSet<string>();
    private Stack<string> forStack = new Stack<string>();

    public List<string> Errors => errors;

    private static readonly string[] forbidden = {
        "PSET", "PRESET", "LINE", "CIRCLE", "DRAW",
        "PAINT", "SCREEN", "PALETTE", "VIEW", "WINDOW",
        "COLOR", "SIN", "COS", "TAN", "ATN", "ASIN",
        "ACOS", "SEC", "CSC", "COT", "DATE$", "TIME$",
        "TIMER", "NOW", "DAY", "MONTH", "YEAR", "HOUR",
        "MINUTE", "SECOND", "RND", "RANDOMIZE"
    };

    public BasicCompiler(string source)
    {
        lines = source.Replace("\r\n", "\n").Split('\n');
    }

    // Validate prohibited instructions and register labels.
    private void Validate()
    {
        for (int i = 0; i < lines.Length; i++)
        {
            string line = lines[i];

            if (Regex.IsMatch(line, @"^\s*\d+\s+") ||
                Regex.IsMatch(line, @"^\s*\d+$"))
            {
                errors.Add(
                    $"[Rule Violation] Line {i + 1}: Line numbers are prohibited.");
            }

            foreach (string word in forbidden)
            {
                if (Regex.IsMatch(line,
                    @"\b" + Regex.Escape(word) + @"\b",
                    RegexOptions.IgnoreCase))
                {
                    errors.Add(
                        $"[Rule Violation] Line {i + 1}: Forbidden identifier '{word}' detected.");
                }
            }

            Match label = Regex.Match(line,
                @"^\s*([A-Za-z_][A-Za-z0-9_]*):");

            if (label.Success)
                labels.Add(label.Groups[1].Value);
        }
    }

    // Main compilation routine.
    public string Compile()
    {
        Validate();

        if (errors.Count > 0)
            return null;

        List<string> body = new List<string>();

        for (int i = 0; i < lines.Length; i++)
        {
            string raw = lines[i];
            string stmt = raw.Trim();

            if (stmt == "")
            {
                body.Add("");
                continue;
            }

            // BASIC comments.
            if (stmt.StartsWith("'") ||
                stmt.StartsWith("REM ", StringComparison.OrdinalIgnoreCase) ||
                stmt.Equals("REM", StringComparison.OrdinalIgnoreCase))
            {
                string comment = stmt.StartsWith("'")
                    ? stmt.Substring(1)
                    : stmt.Substring(3);

                body.Add("    /* " + comment.Trim() + " */");
                continue;
            }

            // Label definition.
            if (Regex.IsMatch(stmt, @"^[A-Za-z_][A-Za-z0-9_]*:$"))
            {
                string label = stmt.Substring(0, stmt.Length - 1);
                body.Add(label + ":;");
                continue;
            }

            try
            {
                string result = TranspileStatement(stmt);

                if (result != null)
                    body.Add("    " + result);
            }
            catch (Exception ex)
            {
                errors.Add($"Line {i + 1}: {ex.Message}");
            }
        }

        if (errors.Count > 0)
            return null;

        return GenerateC(body);
    }

    // Generate the final GCC C source file.
    private string GenerateC(List<string> body)
    {
        StringBuilder output = new StringBuilder();

        output.AppendLine("/* Generated by BASIC to GNU GCC Compiler */");
        output.AppendLine("#define _GNU_SOURCE");
        output.AppendLine("#include <stdio.h>");
        output.AppendLine("#include <stdlib.h>");
        output.AppendLine("#include <string.h>");
        output.AppendLine("#include <math.h>");
        output.AppendLine("#include <ctype.h>");
        output.AppendLine();

        output.AppendLine("/* Runtime String Support Functions */");

        output.AppendLine(
@"static char* _basic_mid(const char* src, int start, int len) {
    int slen = (int)strlen(src);
    if (start < 1) start = 1;
    if (start > slen) return strdup("""");
    int max_len = slen - start + 1;
    if (len > max_len) len = max_len;
    if (len < 0) len = 0;
    char* res = (char*)malloc(len + 1);
    if (!res) return NULL;
    strncpy(res, src + (start - 1), len);
    res[len] = '\0';
    return res;
}");

        output.AppendLine(
@"static char* _basic_ucase(const char* src) {
    char* res = strdup(src);
    for (char* p = res; *p; p++)
        *p = toupper((unsigned char)*p);
    return res;
}");

        output.AppendLine(
@"static char* _basic_lcase(const char* src) {
    char* res = strdup(src);
    for (char* p = res; *p; p++)
        *p = tolower((unsigned char)*p);
    return res;
}");

        output.AppendLine("int main(int argc, char *argv[]) {");
        output.AppendLine("    /* Variable Declarations */");

        foreach (var item in variables)
        {
            if (item.Value == "string")
            {
                output.AppendLine(
                    $"    char {item.Key}[1024] = {{0}};");
            }
            else if (item.Value == "double")
            {
                output.AppendLine(
                    $"    double {item.Key} = 0.0;");
            }
            else
            {
                output.AppendLine(
                    $"    long long {item.Key} = 0LL;");
            }
        }

        output.AppendLine();
        output.AppendLine(string.Join("\n", body));
        output.AppendLine();
        output.AppendLine("    return 0;");
        output.AppendLine("}");

        return output.ToString();
    }

    // Translate a BASIC statement into C.
    private string TranspileStatement(string stmt)
    {
        string up = stmt.ToUpperInvariant();

        // DIM variable AS type.
        Match dim = Regex.Match(stmt,
            @"^DIM\s+([A-Za-z_][A-Za-z0-9_]*)\s+AS\s+(INTEGER|SINGLE|DOUBLE|STRING)$",
            RegexOptions.IgnoreCase);

        if (dim.Success)
        {
            string name = dim.Groups[1].Value;
            string type = dim.Groups[2].Value.ToUpperInvariant();

            string cType = type == "STRING" ? "string" :
                (type == "SINGLE" || type == "DOUBLE")
                    ? "double" : "long long";

            variables[name] = cType;

            return $"/* DIM {name} AS {type} */";
        }

        // PRINT.
        if (up.StartsWith("PRINT") &&
            (up.Length == 5 || char.IsWhiteSpace(up[5])))
        {
            return TranslatePrint(stmt.Substring(5).Trim());
        }

        // INPUT.
        if (up.StartsWith("INPUT") &&
            (up.Length == 5 || char.IsWhiteSpace(up[5])))
        {
            return TranslateInput(stmt.Substring(5).Trim());
        }

        // GOTO.
        Match go = Regex.Match(stmt,
            @"^GOTO\s+([A-Za-z_][A-Za-z0-9_]*)$",
            RegexOptions.IgnoreCase);

        if (go.Success)
            return $"goto {go.Groups[1].Value};";

        // IF.
        if (up.StartsWith("IF "))
            return TranslateIf(stmt);

        // END IF.
        if (up == "END IF" || up == "ENDIF")
            return "}";

        // ELSE.
        if (up == "ELSE")
            return "} else {";

        // FOR.
        Match fm = Regex.Match(stmt,
            @"^FOR\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.+?)\s+TO\s+(.+?)(?:\s+STEP\s+(.+))?$",
            RegexOptions.IgnoreCase);

        if (fm.Success)
        {
            string v = fm.Groups[1].Value;
            string start = TranslateExpression(fm.Groups[2].Value);
            string end = TranslateExpression(fm.Groups[3].Value);
            string step = fm.Groups[4].Success
                ? TranslateExpression(fm.Groups[4].Value)
                : "1";

            if (!variables.ContainsKey(v))
                variables[v] = "long long";

            forStack.Push(v);

            return $"for ({v} = ({start}); ({step}) >= 0 ? ({v} <= ({end})) : ({v} >= ({end})); {v} += ({step})) {{";
        }

        // NEXT.
        if (up == "NEXT" || up.StartsWith("NEXT "))
        {
            if (forStack.Count > 0)
                forStack.Pop();

            return "}";
        }

        // WHILE.
        if (up.StartsWith("WHILE "))
        {
            string condition =
                TranslateExpression(stmt.Substring(6).Trim());

            return $"while ({condition}) {{";
        }

        // WEND.
        if (up == "WEND")
            return "}";

        // END.
        if (up == "END")
            return "return 0;";

        // LET or ordinary assignment.
        string assignment = stmt;

        if (up.StartsWith("LET "))
            assignment = stmt.Substring(4).Trim();

        int eq = assignment.IndexOf('=');

        if (eq >= 0)
        {
            string left = assignment.Substring(0, eq).Trim();
            string right = assignment.Substring(eq + 1).Trim();

            if (Regex.IsMatch(left, @"^[A-Za-z_][A-Za-z0-9_]*$"))
            {
                if (!variables.ContainsKey(left))
                {
                    variables[left] =
                        right.StartsWith("\"") ? "string" : "long long";
                }

                string type = variables[left];
                string expr = TranslateExpression(right);

                if (type == "string")
                    return $"snprintf({left}, sizeof({left}), \"%s\", {expr});";

                return $"{left} = {expr};";
            }
        }

        throw new Exception(
            $"Unrecognized or unsupported statement: \"{stmt}\"");
    }

    // Translate BASIC PRINT.
    private string TranslatePrint(string arg)
    {
        string raw = arg.Trim();
        bool trailingSemi = false;

        if (raw.EndsWith(";"))
        {
            trailingSemi = true;
            raw = raw.Substring(0, raw.Length - 1).Trim();
        }

        if (raw == "")
            return trailingSemi ? "" : "printf(\"\\n\");";

        List<(string expr, char? sep)> parts =
            new List<(string, char?)>();

        bool quotes = false;
        StringBuilder current = new StringBuilder();

        for (int i = 0; i < raw.Length; i++)
        {
            char ch = raw[i];

            if (ch == '"' && (i == 0 || raw[i - 1] != '\\'))
                quotes = !quotes;

            if ((ch == ';' || ch == ',') && !quotes)
            {
                if (current.ToString().Trim() != "")
                    parts.Add((current.ToString().Trim(), ch));

                current.Clear();
            }
            else
            {
                current.Append(ch);
            }
        }

        if (current.ToString().Trim() != "")
            parts.Add((current.ToString().Trim(), null));

        StringBuilder format = new StringBuilder();
        List<string> arguments = new List<string>();

        foreach (var part in parts)
        {
            string expr = TranslateExpression(part.expr);

            bool isString =
                part.expr.StartsWith("\"") ||
                part.expr.Contains("$") ||
                part.expr.ToUpperInvariant().Contains("UCASE$") ||
                part.expr.ToUpperInvariant().Contains("MID$") ||
                part.expr.ToUpperInvariant().Contains("LCASE$") ||
                (variables.ContainsKey(part.expr) &&
                 variables[part.expr] == "string");

            format.Append(isString ? "%s" : "%lld");
            arguments.Add(expr);

            if (part.sep == ',')
                format.Append("\\t");
            else if (part.sep == ';')
                format.Append(" ");
        }

        if (!trailingSemi)
            format.Append("\\n");

        return "printf(\"" + format + "\"" +
            (arguments.Count > 0
                ? ", " + string.Join(", ", arguments)
                : "") + ");";
    }

    // Translate BASIC INPUT.
    private string TranslateInput(string arg)
    {
        string prompt = "";
        string target = arg.Trim();

        Match match = Regex.Match(arg,
            "^\"([^\"]*)\"\\s*;\\s*([A-Za-z_][A-Za-z0-9_]*)");

        if (match.Success)
        {
            prompt = match.Groups[1].Value;
            target = match.Groups[2].Value;
        }

        if (!variables.ContainsKey(target))
        {
            variables[target] =
                target.EndsWith("$") ? "string" : "long long";
        }

        string code = "";

        if (prompt != "")
            code += $"printf(\"{prompt} \"); fflush(stdout); ";

        if (variables[target] == "string")
        {
            code +=
                $"if (fgets({target}, sizeof({target}), stdin)) " +
                $"{{ {target}[strcspn({target}, \"\\r\\n\")] = 0; }}";
        }
        else
        {
            code +=
                $"if (scanf(\"%lld\", &{target}) != 1) " +
                $"{{ {target} = 0; }}";
        }

        return code;
    }

    // Translate BASIC IF.
    private string TranslateIf(string stmt)
    {
        int thenIndex =
            stmt.IndexOf(" THEN", StringComparison.OrdinalIgnoreCase);

        if (thenIndex < 0)
            throw new Exception("IF statement missing THEN");

        string condition = stmt.Substring(3, thenIndex - 3).Trim();
        string rest = stmt.Substring(thenIndex + 5).Trim();

        string condC = TranslateExpression(condition);

        if (rest == "")
            return $"if ({condC}) {{";

        Match go = Regex.Match(rest,
            @"^GOTO\s+([A-Za-z_][A-Za-z0-9_]*)$",
            RegexOptions.IgnoreCase);

        if (go.Success)
            return $"if ({condC}) {{ goto {go.Groups[1].Value}; }}";

        int elseIndex =
            rest.IndexOf(" ELSE ", StringComparison.OrdinalIgnoreCase);

        if (elseIndex >= 0)
        {
            string thenStmt = rest.Substring(0, elseIndex).Trim();
            string elseStmt = rest.Substring(elseIndex + 6).Trim();

            return $"if ({condC}) {{\n" +
                $"        {TranspileStatement(thenStmt)}\n" +
                $"    }} else {{\n" +
                $"        {TranspileStatement(elseStmt)}\n" +
                $"    }}";
        }

        return $"if ({condC}) {{\n" +
            $"        {TranspileStatement(rest)}\n" +
            $"    }}";
    }

    // Translate BASIC expressions into C expressions.
    private string TranslateExpression(string expression)
    {
        string output = expression.Trim();

        // Protect string literals.
        List<string> literals = new List<string>();

        output = Regex.Replace(output, "\"(?:\\\\.|[^\"])*\"", m =>
        {
            literals.Add(m.Value);
            return $"__STR_{literals.Count - 1}__";
        });

        // String functions.
        output = Regex.Replace(output,
            @"\bMID\$\s*\(([^,]+),([^,]+),([^)]+)\)",
            m => "_basic_mid(" +
                TranslateExpression(m.Groups[1].Value) + ", " +
                TranslateExpression(m.Groups[2].Value) + ", " +
                TranslateExpression(m.Groups[3].Value) + ")",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output,
            @"\bUCASE\$\s*\(([^)]+)\)",
            m => "_basic_ucase(" +
                TranslateExpression(m.Groups[1].Value) + ")",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output,
            @"\bLCASE\$\s*\(([^)]+)\)",
            m => "_basic_lcase(" +
                TranslateExpression(m.Groups[1].Value) + ")",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output,
            @"\bLEN\s*\(([^)]+)\)",
            m => "((long long)strlen(" +
                TranslateExpression(m.Groups[1].Value) + "))",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output,
            @"\bABS\s*\(([^)]+)\)",
            m => "llabs((long long)(" +
                TranslateExpression(m.Groups[1].Value) + "))",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output,
            @"\bSQR\s*\(([^)]+)\)",
            m => "sqrt((double)(" +
                TranslateExpression(m.Groups[1].Value) + "))",
            RegexOptions.IgnoreCase);

        // Logical operators.
        output = Regex.Replace(output, @"\bAND\b", "&&",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output, @"\bOR\b", "||",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output, @"\bNOT\b", "!",
            RegexOptions.IgnoreCase);

        output = Regex.Replace(output, @"\bMOD\b", "%",
            RegexOptions.IgnoreCase);

        output = output.Replace("<>", "!=");

        // BASIC equality.
        output = Regex.Replace(output,
            @"(?<![<>=!])=(?!=)", "==");

        // Restore string literals.
        output = Regex.Replace(output, @"__STR_(\d+)__", m =>
        {
            int index = int.Parse(m.Groups[1].Value);
            return literals[index];
        });

        // BASIC exponentiation.
        output = Regex.Replace(output,
            @"([A-Za-z0-9_]+)\s*\^\s*([A-Za-z0-9_]+)",
            "pow((double)$1, (double)$2)");

        return output;
    }
}

class Program
{
    static void Main(string[] args)
    {
        Console.BackgroundColor = ConsoleColor.White;
        Console.ForegroundColor= ConsoleColor.Black;
        Console.Clear();
        Console.OutputEncoding = Encoding.UTF8;

        string inputFile;
        string outputFile;

        // Get file names from command-line arguments.
        if (args.Length >= 1)
            inputFile = args[0];
        else
        {
            Console.Write("Input BASIC file [source.bas]: ");
            inputFile = Console.ReadLine();

            if (string.IsNullOrWhiteSpace(inputFile))
                inputFile = "source.bas";
        }

        if (args.Length >= 2)
            outputFile = args[1];
        else
        {
            Console.Write("Output C file [translated_program.c]: ");
            outputFile = Console.ReadLine();

            if (string.IsNullOrWhiteSpace(outputFile))
                outputFile = "translated_program.c";
        }

        Console.WriteLine();
        Console.WriteLine("==========================================");
        Console.WriteLine(" BASIC to GNU GCC C Compiler");
        Console.WriteLine("==========================================");
        Console.WriteLine();

        try
        {
            if (!File.Exists(inputFile))
            {
                Console.WriteLine("ERROR: Input file not found: " + inputFile);
                Environment.ExitCode = 1;
                return;
            }

            string source = File.ReadAllText(inputFile);

            Console.WriteLine("Input file : " + inputFile);
            Console.WriteLine("Output file: " + outputFile);
            Console.WriteLine();

            BasicCompiler compiler = new BasicCompiler(source);

            string result = compiler.Compile();

            if (compiler.Errors.Count > 0)
            {
                //Console.ForegroundColor = ConsoleColor.Red;

                Console.WriteLine(
                    "Compilation Failed (" +
                    compiler.Errors.Count + " errors)");

                foreach (string error in compiler.Errors)
                    Console.WriteLine("  " + error);

                //Console.ResetColor();

                Console.WriteLine();
                Console.WriteLine("No C file generated.");

                Environment.ExitCode = 1;
                return;
            }

            File.WriteAllText(
                outputFile,
                result,
                new UTF8Encoding(false));

            //Console.ForegroundColor = ConsoleColor.Green;
            Console.WriteLine("Successfully Compiled!");
            Console.WriteLine("0 Errors.");
            //Console.ResetColor();

            Console.WriteLine();
            Console.WriteLine("GNU GCC compatible C code generated.");
            Console.WriteLine();
            Console.WriteLine("Build command:");
            Console.WriteLine(
                "gcc -std=c99 -O2 " +
                outputFile + " -o program -lm");

            Console.WriteLine();
            Console.WriteLine("Output saved to: " + outputFile);
        }
        catch (Exception ex)
        {
            //Console.ForegroundColor = ConsoleColor.Red;
            Console.WriteLine("FATAL ERROR: " + ex.Message);
            //Console.ResetColor();

            Environment.ExitCode = 1;
        }
    }
}
